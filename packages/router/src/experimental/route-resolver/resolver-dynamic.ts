/**
 * Replaces the `path` of a record type with one that also accepts the classic
 * string syntax.
 *
 * @internal
 */
export type RouteRecordWithClassicPath<TRecord> = TRecord extends unknown
  ? Omit<TRecord, 'path'> & { path: MatcherPatternPath | string }
  : never

/**
 * Record accepted by {@link EXPERIMENTAL_ResolverDynamic.addRoute}: a raw
 * route record whose `path` can be a string with the classic syntax (e.g.
 * `/users/:id`), or an already normalized record (e.g. generated by
 * `vue-router/auto-resolver`). Raw records are normalized with
 * `normalizeRouteRecord()`.
 */
export type EXPERIMENTAL_ResolverDynamicRecordRaw =
  | RouteRecordWithClassicPath<EXPERIMENTAL_RouteRecord_Matchable>
  | EXPERIMENTAL_RouteRecordNormalized_Matchable

/**
 * Resolver that allows adding and removing routes at runtime. Created with
 * {@link createDynamicResolver}.
 */
export interface EXPERIMENTAL_ResolverDynamic<
  TRecord = EXPERIMENTAL_RouteRecordNormalized_Matchable,
> extends EXPERIMENTAL_Resolver_Base<TRecord> {
  /**
   * Adds an already normalized route record, e.g. one generated by
   * `vue-router/auto-resolver`. It is added as is.
   *
   * @param record - normalized record to add
   * @returns the record
   */
  addRoute(record: EXPERIMENTAL_RouteRecordNormalized_Matchable): TRecord
  /**
   * Adds a route record. A record with the same name replaces the existing
   * one. Records are ranked by their path like the classic router: more
   * specific paths are matched first. The `props` option is type checked
   * against the components and the params of the route.
   *
   * @param record - record to add
   * @returns the normalized record. Pass it as the `parent` of child records
   * or to {@link removeRoute}.
   */
  addRoute<
    const Name extends RecordName,
    Components extends Record<string, RawRouteComponent> = {},
  >(
    record: RouteRecordWithTypedProps<
      RouteRecordWithClassicPath<EXPERIMENTAL_RouteRecord_Matchable>,
      RouteLocationForRecordName<Name>,
      Components
    > & { name: Name }
  ): TRecord

  /**
   * Removes a route by its name or its record. Records whose `parent` or
   * `aliasOf` chain includes it are removed too.
   *
   * @param nameOrRecord - name or record of the route to remove
   */
  removeRoute(nameOrRecord: RecordName | EXPERIMENTAL_ResolverRecord_Base): void

  /**
   * Removes all the routes.
   */
  clearRoutes(): void
}

/**
 * Creates a resolver that allows adding and removing routes at runtime. Raw
 * records are normalized. Paths written as strings use the classic syntax and
 * are parsed at runtime. They must be absolute: a child record does not
 * inherit the path of its parent.
 *
 * @param records - initial records
 *
 * @example
 * ```ts
 * const resolver = createDynamicResolver([
 *   { name: 'home', path: '/', components: { default: Home } },
 *   { name: 'user', path: '/users/:id(\\d+)', components: { default: User } },
 * ])
 * const about = resolver.addRoute({
 *   name: 'about',
 *   path: '/about',
 *   components: { default: About },
 * })
 * resolver.addRoute({
 *   name: 'about-team',
 *   path: '/about/team',
 *   components: { default: Team },
 *   parent: about,
 * })
 * resolver.removeRoute('about') // also removes 'about-team'
 * ```
 */
export function createDynamicResolver(
  records: EXPERIMENTAL_ResolverDynamicRecordRaw[] = []
): EXPERIMENTAL_ResolverDynamic {
  type TRecord = EXPERIMENTAL_RouteRecordNormalized_Matchable
  // ordered matchable records, aliases included
  const matchers: TRecord[] = []
  // original (non alias) records by name
  const recordMap = new Map<RecordName, TRecord>()
  const scores = new WeakMap<EXPERIMENTAL_ResolverRecord_Base, PathScore>()

  function getScore(record: EXPERIMENTAL_ResolverRecord_Base): PathScore {
    let score = scores.get(record)
    if (!score) scores.set(record, (score = getPatternScore(record.path!)))
    return score
  }

  /**
   * Binary search of the insertion index of a record. Among equal scores, new
   * records go last, but a descendant always goes before its ancestors.
   */
  function findInsertionIndex(record: TRecord): number {
    const score = getScore(record)
    let lower = 0
    let upper = matchers.length

    while (lower !== upper) {
      const mid = (lower + upper) >> 1
      if (comparePathScore(score, getScore(matchers[mid])) < 0) {
        upper = mid
      } else {
        lower = mid + 1
      }
    }

    for (let ancestor = record.parent; ancestor; ancestor = ancestor.parent) {
      if (
        ancestor.path &&
        ancestor.name != null &&
        !comparePathScore(score, getScore(ancestor))
      ) {
        const index = matchers.indexOf(ancestor as TRecord)
        if (index > -1) upper = index
        break
      }
    }

    return upper
  }

  function addRoute(raw: EXPERIMENTAL_ResolverDynamicRecordRaw): TRecord {
    // generated records are already normalized and referenced by their children
    const record =
      'leaveGuards' in raw
        ? raw
        : normalizeRouteRecord(
            (typeof raw.path === 'string'
              ? { ...raw, path: parseClassicPath(raw.path) }
              : raw) as EXPERIMENTAL_RouteRecord_Matchable
          )
    if (!record.aliasOf) {
      const existing = recordMap.get(record.name)
      if (existing) removeRoute(existing)
      recordMap.set(record.name, record)
    }
    matchers.splice(findInsertionIndex(record), 0, record)
    return record
  }

  function removeRoute(
    nameOrRecord: RecordName | EXPERIMENTAL_ResolverRecord_Base
  ) {
    const target = isRouteName(nameOrRecord)
      ? recordMap.get(nameOrRecord)
      : nameOrRecord
    if (!target) {
      if (__DEV__) {
        diagnostics.VUE_ROUTER_R0002({ name: String(nameOrRecord) })
      }
      return
    }

    for (let i = matchers.length - 1; i >= 0; i--) {
      const record = matchers[i]
      if (dependsOn(record, target)) {
        matchers.splice(i, 1)
        if (recordMap.get(record.name) === record) {
          recordMap.delete(record.name)
        }
      }
    }
  }

  records.forEach(addRoute)

  return {
    resolve: createResolve(matchers, recordMap),
    getRoutes: () => matchers,
    getRoute: name => recordMap.get(name),
    addRoute,
    removeRoute,
    clearRoutes() {
      matchers.length = 0
      recordMap.clear()
    },
  }
}

/**
 * Is `record` the `target`, or does its `parent` or `aliasOf` chain lead to it.
 */
function dependsOn(
  record: EXPERIMENTAL_ResolverRecord_Base | null | undefined,
  target: EXPERIMENTAL_ResolverRecord_Base
): boolean {
  return (
    !!record &&
    (record === target ||
      dependsOn(record.aliasOf, target) ||
      dependsOn(record.parent, target))
  )
}

/**
 * Computes the score of a path pattern. Custom patterns rank last, in
 * insertion order.
 */
function getPatternScore(pattern: MatcherPatternPath): PathScore {
  return pattern instanceof MatcherPatternPathDynamic
    ? getPathScore(
        pattern.pathParts,
        Object.values(
          pattern.params as Record<
            string,
            MatcherPatternPathDynamic_ParamOptions
          >
        )
      )
    : pattern instanceof MatcherPatternPathStatic
      ? getPathScore(pattern.path.split('/').filter(Boolean), [])
      : []
}
